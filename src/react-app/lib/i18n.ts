/**
 * The message catalogue.
 *
 * The English strings are `interfaces.md` §17 **verbatim**. That is a hard rule
 * rather than a style preference: the spec's own §0 says the copy table must be
 * used character for character, because the interface being rebuilt is defined
 * partly by its words. So `Login to the` really does end mid-sentence (the site
 * title is appended to it) and `Find and Replace` really is both a label and its
 * own description — those are recorded quirks (§18), not mistakes to fix.
 *
 * Keys are dotted names rather than the English text, so rewording English does
 * not invalidate every translation and so a key can be found by searching for
 * where it is used. A missing translation falls back to English, never to the
 * key: `ZH` is deliberately `Partial`, and an untranslated string shows English
 * — correct, if not translated — instead of leaking `toolbar.mkdir` on screen.
 *
 * There is no plural engine. English inflects its nouns and Chinese does not, so
 * a message that needs two forms has two keys and the caller picks with
 * `translateCount`.
 */

