export function isLocale(value: unknown): value is Locale {
	return typeof value === "string" && (LOCALES as readonly string[]).includes(value);
}

/**
 * A language tag as one of ours.
 *
 * Browsers report full tags — `zh-CN`, `zh-Hant-TW`, `en-GB` — and the region and
 * script are not distinctions this app makes, so only the primary subtag is read.
 * Anything unrecognised is English, which is also what a browser reporting
 * nothing at all gets.
 */
export function localeFrom(tag: string | undefined | null): Locale {
	const primary = (tag ?? "").toLowerCase().split("-")[0];
	return isLocale(primary) ? primary : DEFAULT_LOCALE;
}

/**
 * `{{name}}` substitution.
 *
 * A placeholder with no matching parameter is left standing rather than blanked:
 * a visible `{{count}}` on screen is a bug report, while a silently empty string
 * is a mystery.
 */
export function interpolate(template: string, params: MessageParams = {}): string {
	return template.replace(/\{\{(\w+)\}\}/g, (placeholder, name: string) =>
		name in params ? String(params[name]) : placeholder,
	);
}

/** The message for `key` in `locale`, falling back to English. */
export function translate(locale: Locale, key: MessageKey, params?: MessageParams): string {
	const template = (locale === "zh" ? ZH[key] : undefined) ?? EN[key];
	return params ? interpolate(template, params) : template;
}

/**
 * A count with its noun agreeing.
 *
 * Two keys rather than one, because English inflects the noun and Chinese does
 * not. `{{count}}` is provided for free, so the caller only passes what else the
 * sentence needs.
 */
export function translateCount(
	locale: Locale,
	count: number,
	one: MessageKey,
	other: MessageKey,
	params?: MessageParams,
): string {
	return translate(locale, count === 1 ? one : other, { count, ...params });
}
